void main() {
  // Kode : Symbol
  // Symbol bisa dibuat dengan tanda #
  var symbol1 = #rizal;
  print(symbol1);
  print('');

  // Symbol dengan nama mengandung spasi menggunakan konstruktor
  var symbol2 = Symbol('Mochamad Abu Rizal');
  print(symbol2);
  print('');

  // Symbol bisa digunakan sebagai constant
  const symbol3 = #dart;
  print(symbol3);
}
