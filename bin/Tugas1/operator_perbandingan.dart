void main() {
  // Kode : Operator Perbandingan
  var a = 10;
  var b = 20;
  var c = 10;

  // Sama dengan (==)
  print(a == c);
  // Tidak sama dengan (!=)
  print(a != b);
  // Lebih dari (>)
  print(b > a);
  // Kurang dari (<)
  print(a < b);
  // Lebih dari atau sama dengan (>=)
  print(a >= c);
  // Kurang dari atau sama dengan (<=)
  print(a <= b);
}
