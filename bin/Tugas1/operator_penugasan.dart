void main() {
  // Kode : Operator Penugasan
  num a = 10;

  a += 10;
  print(a);
  a -= 10;
  print(a);
  a *= 10;
  print(a);
  a /= 10;
  print(a);
  a ~/= 10;
  print(a);
  a %= 10;
  print(a);
  print('');

  // Kode : Increment dan Decrement
  var b = 10;

  print(++b);
  print(b++);
  print(b);
  print(--b);
  print(b--);
  print(b);
}
