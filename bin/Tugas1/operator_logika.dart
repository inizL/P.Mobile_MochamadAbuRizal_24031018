void main() {
  // Kode : Operator Logika
  // && = Dan, || = Atau, ! = Kebalikan

  // Operasi &&
  print(true && true);
  print(true && false);
  print(false && true);
  print(false && false);
  print('');

  // Operasi ||
  print(true || true);
  print(true || false);
  print(false || true);
  print(false || false);
  print('');

  // Operasi !
  print(!true);
  print(!false);
}
